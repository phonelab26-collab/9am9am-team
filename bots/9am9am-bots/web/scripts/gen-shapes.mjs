// Generates src/avatar/shapes.gen.ts from the Paper export's shape SVGs.
// Each shape keeps its full path (eyes are evenodd holes) plus the body outline subpath,
// which we paint white underneath so the eyes read as white on any background.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '../artwork');
const sources = {
  blob: 'shapes/blob-orange.svg', cloud: 'shapes/cloud-orange.svg', clover: 'shapes/clover-orange.svg',
  flower: 'shapes/flower-orange.svg', heart: 'shapes/heart-orange.svg', hex: 'shapes/hex-orange.svg',
  house: 'shapes/house-orange.svg', sparkle: 'shapes/sparkle-orange.svg', square: 'shapes/square-orange.svg',
  star: 'shapes/star-orange.svg', tablet: 'shapes/tablet-orange.svg', teardrop: 'shapes/teardrop-orange.svg',
  wedge: 'shapes/wedge-orange.svg',
  // Extra silhouettes only present as rendered avatars.
  egg: 'avatars/dr-eggbot-yc-bookface.svg', pebble: 'avatars/jules-personal-website.svg',
};
const out = {};
for (const [name, rel] of Object.entries(sources)) {
  const svg = fs.readFileSync(path.join(root, rel), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const d = svg.match(/ d="([^"]+)"/)[1];
  const subs = d.split(/(?=M)/).map((s) => s.trim()).filter(Boolean);
  const area = (s) => {
    const n = s.match(/-?\d+(\.\d+)?/g).map(Number);
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    for (let i = 0; i + 1 < n.length; i += 2) { x0 = Math.min(x0, n[i]); x1 = Math.max(x1, n[i]); y0 = Math.min(y0, n[i + 1]); y1 = Math.max(y1, n[i + 1]); }
    return (x1 - x0) * (y1 - y0);
  };
  const outline = subs.reduce((a, b) => (area(b) > area(a) ? b : a));
  out[name] = { viewBox, d, outline };
}
const body = `// AUTO-GENERATED by scripts/gen-shapes.mjs from web/artwork. Do not edit.\nexport interface ShapeDef { viewBox: string; d: string; outline: string }\nexport const SHAPES: Record<string, ShapeDef> = ${JSON.stringify(out)};\n`;
fs.writeFileSync(path.resolve(import.meta.dirname, '../src/avatar/shapes.gen.ts'), body);
console.log('shapes:', Object.keys(out).join(', '), (body.length / 1024).toFixed(1) + 'KB');
